    /**
     * Convert BS date string (YYYY-MM-DD) to AD date string (YYYY-MM-DD).
     */
    public static function bsToAd(string $bsDate): string
    {
        [$bsY, $bsM, $bsD] = array_map('intval', explode('-', $bsDate));

        $totalDays = $bsD - 1;

        // Sum days in all complete months of the current BS year
        $yearIdx = $bsY - 2000;
        $yearData = self::$bsData[$yearIdx] ?? null;
        if ($yearData === null) {
            throw new \InvalidArgumentException("BS year $bsY not in supported range (2000–2090)");
        }
        for ($m = 1; $m < $bsM; $m++) {
            $totalDays += $yearData[$m];
        }

        // Sum all days in prior BS years from 2000
        for ($y = 0; $y < $yearIdx; $y++) {
            $totalDays += self::$bsData[$y][0];
        }

        // Add to AD base date
        $adDate = \DateTime::createFromFormat(
            'Y-n-j',
            self::AD_BASE_YEAR . '-' . self::AD_BASE_MONTH . '-' . self::AD_BASE_DAY
        );
        $adDate->modify("+$totalDays days");

        return $adDate->format('Y-m-d');
    }

    /**
     * Convert AD date string (YYYY-MM-DD) to BS date string (YYYY-MM-DD).
     */
    public static function adToBs(string $adDate): string
    {
        $ad = \DateTime::createFromFormat('Y-m-d', $adDate);
        $base = \DateTime::createFromFormat(
            'Y-n-j',
            self::AD_BASE_YEAR . '-' . self::AD_BASE_MONTH . '-' . self::AD_BASE_DAY
        );

        $totalDays = (int) $base->diff($ad)->days;

        $bsYear = 2000;
        foreach (self::$bsData as $idx => $yearData) {
            if ($totalDays < $yearData[0]) {
                $bsYear = 2000 + $idx;
                break;
            }
            $totalDays -= $yearData[0];
        }

        $yearIdx  = $bsYear - 2000;
        $yearData = self::$bsData[$yearIdx];
        $bsMonth  = 1;
        for ($m = 1; $m <= 12; $m++) {
            if ($totalDays < $yearData[$m]) {
                $bsMonth = $m;
                break;
            }
            $totalDays -= $yearData[$m];
        }

        $bsDay = $totalDays + 1;

        return sprintf('%04d-%02d-%02d', $bsYear, $bsMonth, $bsDay);
    }

    /**
     * Return the current date in BS (YYYY-MM-DD).
     */
    public static function todayBs(): string
    {
        return self::adToBs(date('Y-m-d'));
    }

    /**
     * Return the BS month name.
     */
    public static function monthName(int $month, string $lang = 'en'): string
    {
        if ($lang === 'np') {
            return self::$monthNamesNp[$month] ?? '';
        }
        return self::$monthNamesEn[$month] ?? '';
    }

    /**
     * Return the number of days in a BS month.
     */
    public static function daysInMonth(int $bsYear, int $bsMonth): int
    {
        $idx = $bsYear - 2000;
        return self::$bsData[$idx][$bsMonth] ?? 0;
    }

    /**
     * Convert ASCII digits to Devanagari digits for display.
     */
    public static function toDevanagariDigits(string $number): string
    {
        return strtr($number, '0123456789', '०१२३४५६७८९');
    }
